export type PriceItem = {
  /**
   * Постоянный ключ позиции для расчёта стоимости (src/content/estimate.ts)
   * и схемы импланта. Есть только у позиций, которые там участвуют. Если
   * позиция пропадёт из прайса, сборка упадёт с понятной ошибкой.
   */
  id?: string;
  name: string;
  price: number;
  /** Единица расчёта из прайса: «1 зуб», «1 визит». */
  unit?: string;
  /** «от» — когда сумма зависит от случая. */
  from?: boolean;
  /** Показывать на странице услуги. */
  featured?: boolean;
};

export type PriceSection = {
  /** Якорь раздела. У разделов услуг совпадает со slug услуги — на него ссылается её страница. */
  id: string;
  title: string;
  /** Ссылка на страницу услуги, если она есть. */
  service?: string;
  items: PriceItem[];
};

