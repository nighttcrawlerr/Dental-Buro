import { ViewTransition } from "react";

/**
 * Переход между страницами: старая быстро гаснет, новая проявляется.
 *
 * Шаблон, а не layout: layout живёт между переходами, и у обёртки в нём не
 * бывает ни появления, ни ухода. Шаблон пересоздаётся на каждый переход.
 * Между двумя врачами или двумя услугами он не пересоздаётся — сегмент
 * верхнего уровня тот же, — и там работает только перетекание общих
 * элементов (портрет, карточка услуги).
 *
 * Без сдвига по вертикали: у первых экранов свои анимации по таймеру, и
 * второе движение поверх них превращает переход в кашу.
 */
export default function Template({ children }: { children: React.ReactNode }) {
  return (
    <ViewTransition enter="page-enter" exit="page-exit" default="none">
      <div>{children}</div>
    </ViewTransition>
  );
}
