import { ViewTransition } from "react";

/**
 * Переход между страницами: новая страница плавно проявляется.
 *
 * Только появление, без ухода старой. Чтобы погасить старую страницу,
 * браузер фотографирует её во всю высоту: у страницы услуги это ~5700px, на
 * ретине — текстура больше 100 МБ. Замер с настоящей видеокартой показал
 * провал в 100–130 мс сразу после клика; без снимка старой страницы — ни
 * одного. Новая рисуется вживую и такой цены не имеет. Фон у страниц общий
 * кремовый, поэтому смена читается как проявление, а не как скачок.
 *
 * Шаблон, а не layout: layout живёт между переходами, и у обёртки в нём не
 * бывает появления. Шаблон пересоздаётся на каждый переход. Между двумя
 * врачами или двумя услугами он не пересоздаётся — сегмент верхнего уровня
 * тот же, — и там работает только перетекание общих элементов (портрет,
 * карточка услуги).
 */
export default function Template({ children }: { children: React.ReactNode }) {
  return (
    <ViewTransition enter="page-enter" exit="none" default="none">
      <div>{children}</div>
    </ViewTransition>
  );
}
